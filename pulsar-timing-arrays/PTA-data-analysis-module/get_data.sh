#!/usr/bin/env bash
# =============================================================================
#  PTA Lab -- NANOGrav 15-Year Data Download Script
#  Nathan Steinle
#
#  Usage:
#      bash get_data.sh                     # downloads to ./NG15yr_data/
#      bash get_data.sh /path/to/data/dir   # custom directory
#
#  Run AFTER setup.sh.
#
#  Downloads:
#    - NANOGrav 15-yr par + tim files (narrowband, canonical only)
#      Source: Zenodo DOI 10.5281/zenodo.16051178  (~639 MB tarball)
#    - Clock correction files (inside the same tarball)
#
#  Writes:  pta_paths.sh  (in this directory AND in the data directory)
#  The notebook reads pta_paths.sh to locate the data automatically.
#
#  Resumable: re-running skips files already present.
# =============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DATA_ROOT="${1:-${SCRIPT_DIR}/NG15yr_data}"

TARBALL_URL="https://zenodo.org/records/16051178/files/NANOGrav15yr_PulsarTiming_v2.1.0.tar.gz"
TARBALL_NAME="NANOGrav15yr_PulsarTiming_v2.1.0.tar.gz"
TARBALL_MD5="557d42dd8486a5f8272d90dec9b228a8"

EXTRACT_DIR="${DATA_ROOT}/NANOGrav15yr_PulsarTiming_v2.1.0"
PAR_DIR="${EXTRACT_DIR}/narrowband/par"
TIM_DIR="${EXTRACT_DIR}/narrowband/tim"
CLOCK_DIR="${EXTRACT_DIR}/clock"

GREEN='\033[0;32m'; YELLOW='\033[1;33m'; RED='\033[0;31m'; NC='\033[0m'
log()  { echo -e "\n${GREEN}== $* ${NC}"; }
warn() { echo -e "${YELLOW}  W  $*${NC}"; }
die()  { echo -e "${RED}  X  $*${NC}"; exit 1; }

fetch() {
    local url="$1" dest="$2" label="${3:-$(basename "$2")}"
    if [ -s "$dest" ]; then
        echo "  Already present: $label"
    else
        echo "  Downloading $label ..."
        curl -L --progress-bar --retry 3 --retry-delay 5 "$url" -o "$dest"
        echo "  Saved: $dest"
    fi
}

check_md5() {
    local file="$1" expected="$2"
    if command -v md5sum &>/dev/null; then
        actual="$(md5sum "$file" | awk '{print $1}')"
    elif command -v md5 &>/dev/null; then
        actual="$(md5 -q "$file")"
    else
        warn "md5sum not available -- skipping checksum"; return
    fi
    [ "$actual" = "$expected" ] && echo "  MD5 verified." \
        || warn "MD5 mismatch -- file may be corrupted; delete and re-run."
}

# Count canonical par/tim files (skip NoRedNoise and predictive variants)
count_canonical() {
    local dir="$1" ext="$2"
    find "$dir" -maxdepth 1 -name "*.$ext" | while read -r f; do
        stem="$(basename "$f" ".$ext")"
        case "$stem" in
            *.NoRedNoise|*.predictive|*.10yr) ;;
            *) echo "$f" ;;
        esac
    done | wc -l
}

log "Checking prerequisites"
command -v curl &>/dev/null || die "curl is required but not installed."
command -v tar  &>/dev/null || die "tar is required but not installed."
echo "  curl and tar available."

log "Creating data directory: $DATA_ROOT"
mkdir -p "$DATA_ROOT"

log "Downloading NANOGrav 15-yr tarball"
echo "  (~639 MB -- this will take a few minutes)"
TARBALL_PATH="${DATA_ROOT}/${TARBALL_NAME}"
fetch "$TARBALL_URL" "$TARBALL_PATH" "$TARBALL_NAME"
check_md5 "$TARBALL_PATH" "$TARBALL_MD5"

if [ -d "$PAR_DIR" ] && [ "$(ls -A "$PAR_DIR" 2>/dev/null | wc -l)" -gt 0 ]; then
    echo "  Already extracted: $PAR_DIR"
else
    echo "  Extracting tarball ..."
    tar -xzf "$TARBALL_PATH" -C "$DATA_ROOT"
    echo "  Extracted to: $EXTRACT_DIR"
fi

N_PAR_ALL="$(ls "${PAR_DIR}"/*.par 2>/dev/null | wc -l | tr -d ' ')"
N_PAR_CANON="$(count_canonical "$PAR_DIR" par)"
N_TIM_CANON="$(count_canonical "$TIM_DIR" tim)"
echo ""
echo "  Total par files in directory : $N_PAR_ALL"
echo "  Canonical par files          : $N_PAR_CANON  (expected: 68)"
echo "  Canonical tim files          : $N_TIM_CANON  (expected: 68)"
[ "$N_PAR_CANON" -lt 60 ] && warn "Fewer than 60 canonical par files -- check extraction."

log "Writing path configuration: pta_paths.sh"

write_paths() {
    local dest="$1"
    cat > "$dest" << PATHEOF
# PTA Lab -- Path Configuration
# Auto-generated by get_data.sh  $(date)
# The notebook reads these variables from this file in Cell 1.
# To override any path, edit the values below and re-run Cell 1.

NG15_DATA_ROOT="${DATA_ROOT}"
NG15_PAR_DIR="${PAR_DIR}"
NG15_TIM_DIR="${TIM_DIR}"
NG15_CLOCK_DIR="${CLOCK_DIR}"
PATHEOF
    echo "  Written: $dest"
}

write_paths "${DATA_ROOT}/pta_paths.sh"
write_paths "${SCRIPT_DIR}/pta_paths.sh"

log "Done!"
cat << MSG

  Data root    : $DATA_ROOT
  par directory: $PAR_DIR
  tim directory: $TIM_DIR
  Canonical par: $N_PAR_CANON  tim: $N_TIM_CANON

  pta_paths.sh written to this directory and to the data root.

  Next steps:
    source pta_env/bin/activate
    jupyter lab PTA_Lab_Student.ipynb

MSG
